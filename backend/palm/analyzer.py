def analyze_palm_features(features: Dict[str, Any]) -> Dict[str, Any]:
    """
    Generates a humorous structured reading covering LOVE, CAREER, MONEY, PERSONALITY, FUTURE.
    """
    love = random.choice(LOVE_INTERPRETATIONS)
    career = random.choice(CAREER_INTERPRETATIONS)
    money = random.choice(MONEY_INTERPRETATIONS)
    personality = random.choice(PERSONALITY_INTERPRETATIONS)
    future = random.choice(FUTURE_INTERPRETATIONS)

    summary = (
        f"എടാ ഉണ്ടം പാണ്ടി, കൈ ഞാൻ ഫുൾ നോക്കി! {personality[:60]}... "
        f"പൈസയുടെ കാര്യം {money[:50]}... "
        f"അതൊക്കെ പോട്ടെ, കരിയറിൽ {career[:55]}... തീർന്നടാ!"
    )

    return {
        "reading": {
            "love": love,
            "career": career,
            "money": money,
            "personality": personality,
            "future": future
        },
        "summary": summary,
        "features": features
    }
